"""Render probe results as docs/capability-matrix.md.

The file is committed to a public repo, so it never contains tenant IDs, object
IDs or user IDs, only request shapes, outcomes and Graph error codes.
"""

from __future__ import annotations

import re
from collections.abc import Sequence
from datetime import date

from nhigov.probe.checks import Result

_GUID = re.compile(r"[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}")
# Entra also writes GUIDs as 22-char base64url, e.g. the agent T1 `sub` claim
# `/eid1/c/pub/t/<tenant>/a/<blueprint appId>/<agent id>`.
_B64_GUID_SEGMENT = re.compile(r"(?<=/)[A-Za-z0-9_-]{22}(?=/|$|'|\")")


def redact(text: str) -> str:
    return _B64_GUID_SEGMENT.sub("<b64-id>", _GUID.sub("<id>", text))


def _cell(text: str, limit: int = 120) -> str:
    text = redact(" ".join(text.split())).replace("|", "\\|")
    return text if len(text) <= limit else text[: limit - 1] + "…"


def render_matrix(results: Sequence[Result], recommended_backend: str, run_date: date) -> str:
    lines = [
        "# Capability matrix",
        "",
        f"_Generated by `nhigov probe` on {run_date.isoformat()}. "
        "Do not edit by hand; re-run the probe._",
        "",
        "Outcome meanings: **OK** works on this tenant · **403 permission** missing Graph "
        "permission (free to fix) · **license required** needs P1/P2 · **unavailable / not found** "
        "API or type not present · **planned** write check not executed (dry run).",
        "",
        "| ID | Capability | Identity | Request | Outcome | Graph code / detail | Decides |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in results:
        c = r.check
        detail = " ".join(x for x in (r.code, r.detail) if x)
        lines.append(
            f"| {c.id} | {_cell(c.capability)} | {c.identity} | `{c.method} /{c.version}/"
            f"{_cell(c.path.split('?')[0], 90)}` | {r.outcome.value} | {_cell(detail)} | "
            f"{_cell(c.decides)} |"
        )
    lines += [
        "",
        f"**Recommended identity backend (ADR-003):** `{recommended_backend}`",
        "",
    ]
    return "\n".join(lines)
